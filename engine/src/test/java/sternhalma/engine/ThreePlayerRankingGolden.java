package sternhalma.engine;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.List;

/**
 * Generator of {@code three-player-ranking-golden.tsv}, the file that the C++ port reproduces. The format is documented in
 * the header of the file itself (see {@link #HEADER}); {@code ThreePlayerRankingGoldenTest} checks the committed file against
 * a fresh run of this generator. Rewrite the file with
 * {@code java -cp <engine classes>:<engine test classes> sternhalma.engine.ThreePlayerRankingGolden <path>}.
 */
final class ThreePlayerRankingGolden {

    static final int POSITIONS = 56;

    static final List<String> HEADER = List.of(
            "# Golden positions of the three-player game with ranking=FULL_RANKING (RuleSet.defaults(3), 600 plies), both jump rules.",
            "# Generated by engine/src/test/java/sternhalma/engine/ThreePlayerRankingGolden.java; checked by ThreePlayerRankingGoldenTest.",
            "# One position per line, tab separated, after this header. Columns:",
            "#   id        position number, 0 to 39",
            "#   players   3",
            "#   jump      ADJACENT or LONG (id % 2: 0 = ADJACENT, 1 = LONG)",
            "#   policy    RANDOM, GREEDY, AFTER_FIRST or LIMIT85 (ids 0 to 39: id % 4 < 2: RANDOM, else GREEDY; ids 40 to 47:",
            "#             AFTER_FIRST, a GREEDY playout that stops 7 plies after the first player has finished; ids 48 to 55:",
            "#             LIMIT85, a GREEDY playout with moveLimit 85)",
            "#   limit     the moveLimit of the row: 85 for LIMIT85, else 600",
            "#   seed      seed of the playout; SplitMix64 (the stream of java.util.SplittableRandom, state += 0x9e3779b97f4a7c15)",
            "#   plies     plies played from the start position (RANDOM: at most 6 * id, but rows 36 and 37 play until the game ends; GREEDY: until the game ends)",
            "#   side      the side to move: 0, 1 or 2",
            "#   pieces0   cells of player 0 (cell ids 0..120, ordered by r then q), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form",
            "#   moves     number of legal moves of the side to move",
            "#   sorted    SHA-256 (lower-case hex) of the legal moves sorted ascending by (from, to)",
            "#   ordered   SHA-256 of the same moves in generation order (steps by direction, then hop landings in",
            "#             depth-first order, pieces by ascending cell)",
            "#   hash      Position.hash() as 16 hex digits (Zobrist keys of three players and of the finished players)",
            "#   finished  Position.finishedMask(): bit p is set if player p has finished (filled the goal) and makes no more moves",
            "#   outcome   ONGOING, or REASON/winner/ranking/values: Outcome.reason, Outcome.winner (-1: none), Outcome.ranking",
            "#             (the three players by rank, comma separated) and the three values as the IEEE 754 bit patterns",
            "#             (16 hex digits each), comma separated. NO_MOVES is reported if the side to move has no legal move",
            "#             and the game is not over otherwise. The finished players are skipped in the turn order.",
            "# Move text that is hashed: one line per move, \"<from>-<to>\\n\" with decimal cell ids, UTF-8.",
            "# Playout: rules RuleSet.defaults(3) with FULL_RANKING, moveLimit 600 and the jump rule of the row. At every ply the legal moves are sorted",
            "# ascending by (from, to). RANDOM: the move with index (nextLong() >>> 1) % count is played. GREEDY: among",
            "# the moves with the largest distance gain Layout.distance(mover, from) - Layout.distance(mover, to) the one",
            "# with index (nextLong() >>> 1) % (number of such moves) in sorted order is played. nextLong() is from",
            "# SplitMix64(seed), seed = 0x3EED0000 + id. A playout stops when the game is over (outcome != null), the",
            "# side to move has no move, or (RANDOM rows below 36) the ply limit of the row is reached.",
            "# Cell id of (q, r): cells are numbered 0..120 by ascending r, then ascending q, over the 121 board cells",
            "# (max(q, r, -q-r) <= 4 or min(q, r, -q-r) >= -4).");

    private ThreePlayerRankingGolden() {
    }

    static RuleSet rules(RuleSet.JumpRule jump, int limit) {
        return RuleSet.defaults(3).withRanking(RuleSet.Ranking.FULL_RANKING).withMoveLimit(limit).withJumpRule(jump);
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < POSITIONS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    static String line(int id) {
        RuleSet.JumpRule jump = id % 2 == 0 ? RuleSet.JumpRule.ADJACENT : RuleSet.JumpRule.LONG;
        String policy = id >= 48 ? "LIMIT85" : id >= 40 ? "AFTER_FIRST" : id % 4 >= 2 ? "GREEDY" : "RANDOM";
        boolean greedy = !policy.equals("RANDOM");
        int limit = policy.equals("LIMIT85") ? 85 : 600;
        Position pos = Position.initial(rules(jump, limit));
        int firstFinishedPly = -1;
        SplitMix64 random = new SplitMix64(0x3EED0000L + id);
        int target = greedy || id >= 36 ? Integer.MAX_VALUE : 6 * id; // the last RANDOM rows play to the move limit
        while (pos.ply() < target && pos.outcome() == null
                && !(firstFinishedPly >= 0 && pos.ply() >= firstFinishedPly + 7 && policy.equals("AFTER_FIRST"))) {
            int[] moves = sorted(pos.legalMoves());
            if (moves.length == 0) {
                break;
            }
            int[] candidates = greedy ? bestGain(pos, moves) : moves;
            pos.make(candidates[(int) ((random.nextLong() >>> 1) % candidates.length)]);
            if (firstFinishedPly < 0 && pos.finishedMask() != 0) {
                firstFinishedPly = pos.ply();
            }
        }
        int[] generated = pos.legalMoves();
        Outcome outcome = pos.outcome();
        if (outcome == null && generated.length == 0) {
            outcome = pos.noMovesOutcome();
        }
        return String.join("\t",
                Integer.toString(id), "3", jump.name(), policy, Integer.toString(limit),
                "0x" + Long.toHexString(0x3EED0000L + id).toUpperCase(),
                Integer.toString(pos.ply()), Integer.toString(pos.sideToMove()),
                join(pos.pieces(0)), join(pos.pieces(1)), join(pos.pieces(2)),
                Integer.toString(generated.length), sha256(sorted(generated)), sha256(generated),
                String.format("%016x", pos.hash()), Integer.toString(pos.finishedMask()), outcomeText(outcome));
    }

    static String outcomeText(Outcome outcome) {
        if (outcome == null) {
            return "ONGOING";
        }
        StringBuilder bits = new StringBuilder();
        for (double v : outcome.values()) {
            bits.append(bits.isEmpty() ? "" : ",").append(String.format("%016x", Double.doubleToLongBits(v)));
        }
        return outcome.reason() + "/" + outcome.winner() + "/"
                + String.join(",", Arrays.stream(outcome.ranking()).mapToObj(Integer::toString).toList()) + "/" + bits;
    }

    private static int[] bestGain(Position pos, int[] sortedMoves) {
        int p = pos.sideToMove();
        Layout layout = pos.layout();
        int best = Integer.MIN_VALUE;
        int[] kept = new int[sortedMoves.length];
        int count = 0;
        for (int m : sortedMoves) {
            int gain = layout.distance(p, Move.from(m)) - layout.distance(p, Move.to(m));
            if (gain > best) {
                best = gain;
                count = 0;
            }
            if (gain == best) {
                kept[count++] = m;
            }
        }
        return Arrays.copyOf(kept, count);
    }

    /** Sorted ascending by (from, to); duplicates are kept so that a duplicate changes the hash. */
    static int[] sorted(int[] moves) {
        return Arrays.stream(moves).boxed()
                .sorted((x, y) -> Integer.compare(Move.from(x) << 8 | Move.to(x), Move.from(y) << 8 | Move.to(y)))
                .mapToInt(Integer::intValue).toArray();
    }

    private static String join(int[] cells) {
        return String.join(",", Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    static String sha256(int[] moves) {
        StringBuilder text = new StringBuilder();
        for (int m : moves) {
            text.append(Move.from(m)).append('-').append(Move.to(m)).append('\n');
        }
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(text.toString().getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(digest);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    public static void main(String[] args) throws java.io.IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
