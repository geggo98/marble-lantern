package sternhalma.engine;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;

import sternhalma.engine.RuleSet.ForeignCamps;
import sternhalma.engine.RuleSet.JumpRule;
import sternhalma.engine.RuleSet.TriangleRows;

/**
 * Generator of {@code triangle-rows-golden.tsv}, the file that the C++ port and the web engines reproduce for the
 * switch {@link TriangleRows#FIVE} (15-cell houses on the 121-cell board). The format is documented in the header of
 * the file itself (see {@link #HEADER}); {@code TriangleRowsGoldenTest} checks the committed file against a fresh run
 * of this generator and against {@link TriangleRowsOracle}. Rewrite the file with
 * {@code java -cp <engine classes>:<engine test classes> sternhalma.engine.TriangleRowsGolden <path>}.
 */
final class TriangleRowsGolden {

    /** Positions per variant (camps, players, jump): {@link #RANDOM_ROWS} random playouts, then greedy ones. */
    static final int PER_VARIANT = 8;
    static final int RANDOM_ROWS = 4;
    static final ForeignCamps[] CAMPS = ForeignCamps.values();
    static final int ROWS = CAMPS.length * 2 * JumpRule.values().length * PER_VARIANT;
    /**
     * The last greedy row of a variant stops here at the latest. It is below the 5-row move limits (250 and 375
     * plies), so the file does not depend on them.
     */
    static final int CAP = 240;
    static final long SEED_BASE = 0x15F00000L;

    static final List<String> HEADER = List.of(
            "# Golden positions of the house-size switch RuleSet.TriangleRows FIVE (15-cell houses, 15 pieces per player,",
            "# 121-cell board): two and three players, both jump rules, all three foreign-corner rules, project default",
            "# rules otherwise (RuleSet.defaults(players, FIVE)).",
            "# Generated by engine/src/test/java/sternhalma/engine/TriangleRowsGolden.java; checked by TriangleRowsGoldenTest",
            "# against a fresh run and against TriangleRowsOracle (houses and moves from cube coordinates).",
            "# One position per line, tab separated, after this header. Columns:",
            "#   id        row number, 0 to " + (ROWS - 1),
            "#   players   2 or 3",
            "#   jump      ADJACENT or LONG",
            "#   camps     CLOSED, PASS_THROUGH or OPEN",
            "#   policy    RANDOM (k = id mod " + PER_VARIANT + " < " + RANDOM_ROWS + ") or GREEDY",
            "#   seed      seed of the playout; SplitMix64 (the stream of java.util.SplittableRandom, state += 0x9e3779b97f4a7c15)",
            "#   plies     plies played from the start position; the target is RANDOM 23 * k + 9, GREEDY 30 * (k - 3) for",
            "#             k = 4..6 and " + CAP + " for k = 7; fewer if the game ended earlier",
            "#   side      the side to move: 0, 1 or 2",
            "#   pieces0   cells of player 0 (cell ids 0..120, ordered by r then q), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form; \"-\" with two players",
            "#   moves     number of legal moves of the side to move",
            "#   sorted    SHA-256 (lower-case hex) of the legal moves sorted ascending by (from, to)",
            "#   ordered   SHA-256 of the same moves in generation order (pieces by ascending cell; per piece the steps",
            "#             by direction, then the jump landings in depth-first order)",
            "#   hash      Position.hash() as 16 hex digits",
            "#   initial   Position.hash() of the start position of the variant, 16 hex digits",
            "#   outcome   ONGOING, or REASON/winner/values: Outcome.reason, Outcome.winner (-1: none) and the values as",
            "#             IEEE 754 bit patterns (16 hex digits each), comma separated. NO_MOVES is reported if the side to",
            "#             move has no legal move and the game is not over otherwise.",
            "# Move text that is hashed: one line per move, \"<from>-<to>\\n\" with decimal cell ids, UTF-8.",
            "# Playout: at every ply the legal moves are sorted ascending by (from, to). RANDOM plays the move with index",
            "# (nextLong() >>> 1) % count; GREEDY keeps the moves with the largest gain Layout.distance(p, from) -",
            "# Layout.distance(p, to) (distances to the 15-cell goal house) in the same order and plays the one with index",
            "# (nextLong() >>> 1) % kept, with nextLong() from SplitMix64(seed). seed = 0x15F00000 + id.",
            "# A playout stops early if the game is over (outcome != null) or the side to move has no move.",
            "# The file does not depend on the move limit as long as it is above " + CAP + " plies.",
            "# Row order: camps (CLOSED, PASS_THROUGH, OPEN), then players (2, 3), then jump (ADJACENT, LONG), then k.");

    private TriangleRowsGolden() {
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < ROWS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    static RuleSet rules(int id) {
        int variant = id / PER_VARIANT;
        JumpRule jump = JumpRule.values()[variant % 2];
        int players = 2 + (variant / 2) % 2;
        ForeignCamps camps = CAMPS[variant / 4];
        return RuleSet.defaults(players, TriangleRows.FIVE).withJumpRule(jump).withForeignCamps(camps);
    }

    static boolean greedy(int id) {
        return id % PER_VARIANT >= RANDOM_ROWS;
    }

    static int target(int id) {
        int k = id % PER_VARIANT;
        if (k < RANDOM_ROWS) {
            return 23 * k + 9;
        }
        return k == PER_VARIANT - 1 ? CAP : 30 * (k - RANDOM_ROWS + 1);
    }

    static long seed(int id) {
        return SEED_BASE + id;
    }

    /**
     * Plays the playout of row {@code id} and hands every position before a move, and the final one, to the
     * visitor. Returns the final position.
     */
    static Position play(int id, java.util.function.Consumer<Position> visitor) {
        Position pos = Position.initial(rules(id));
        SplitMix64 random = new SplitMix64(seed(id));
        int target = target(id);
        boolean greedy = greedy(id);
        while (pos.ply() < target && pos.outcome() == null) {
            visitor.accept(pos);
            int[] moves = LongJumpGolden.sorted(pos.legalMoves());
            if (moves.length == 0) {
                break;
            }
            int[] candidates = greedy ? bestGain(pos, moves) : moves;
            pos.make(candidates[(int) ((random.nextLong() >>> 1) % candidates.length)]);
        }
        visitor.accept(pos);
        return pos;
    }

    static String line(int id) {
        RuleSet rules = rules(id);
        Position pos = play(id, p -> { });
        int[] generated = pos.legalMoves();
        Outcome outcome = pos.outcome();
        if (outcome == null && generated.length == 0) {
            outcome = pos.noMovesOutcome();
        }
        return String.join("\t",
                Integer.toString(id), Integer.toString(rules.players()), rules.jumpRule().name(),
                rules.foreignCamps().name(), greedy(id) ? "GREEDY" : "RANDOM",
                "0x" + Long.toHexString(seed(id)).toUpperCase(Locale.ROOT),
                Integer.toString(pos.ply()), Integer.toString(pos.sideToMove()),
                join(pos.pieces(0)), join(pos.pieces(1)), rules.players() == 3 ? join(pos.pieces(2)) : "-",
                Integer.toString(generated.length), LongJumpGolden.sha256(LongJumpGolden.sorted(generated)),
                LongJumpGolden.sha256(generated), hex(pos.hash()), hex(Position.initial(rules).hash()),
                ThreePlayerGolden.outcomeText(outcome));
    }

    static String hex(long hash) {
        return String.format(Locale.ROOT, "%016x", hash);
    }

    private static int[] bestGain(Position pos, int[] sortedMoves) {
        int p = pos.sideToMove();
        Layout layout = pos.layout();
        int best = Integer.MIN_VALUE;
        int[] kept = new int[sortedMoves.length];
        int count = 0;
        for (int m : sortedMoves) {
            int gain = layout.distance(p, Move.from(m)) - layout.distance(p, Move.to(m));
            if (gain > best) {
                best = gain;
                count = 0;
            }
            if (gain == best) {
                kept[count++] = m;
            }
        }
        return Arrays.copyOf(kept, count);
    }

    private static String join(int[] cells) {
        return String.join(",", Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    public static void main(String[] args) throws java.io.IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
