package sternhalma.engine;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;

import sternhalma.engine.RuleSet.ForeignCamps;
import sternhalma.engine.RuleSet.JumpRule;

/**
 * Generator of {@code foreign-camps-golden.tsv}, the file that the C++ port reproduces for the switch
 * {@link ForeignCamps}. The format is documented in the header of the file itself (see {@link #HEADER});
 * {@code ForeignCampsGoldenTest} checks the committed file against a fresh run of this generator. Rewrite the file with
 * {@code java -cp <engine classes>:<engine test classes> sternhalma.engine.ForeignCampsGolden <path>}.
 */
final class ForeignCampsGolden {

    /** Positions per variant (camps, players, jump). */
    static final int PER_VARIANT = 6;
    static final ForeignCamps[] CAMPS = {ForeignCamps.PASS_THROUGH, ForeignCamps.OPEN};
    static final int ROWS = CAMPS.length * 2 * JumpRule.values().length * PER_VARIANT;

    static final List<String> HEADER = List.of(
            "# Golden moves of the foreign-corner switch (RuleSet.ForeignCamps PASS_THROUGH and OPEN), two and three players,",
            "# both jump rules, project default rules otherwise (RuleSet.defaults(players)).",
            "# Generated by engine/src/test/java/sternhalma/engine/ForeignCampsGolden.java; checked by ForeignCampsGoldenTest.",
            "# One position per line, tab separated, after this header. Columns:",
            "#   id        row number, 0 to " + (ROWS - 1),
            "#   players   2 or 3",
            "#   jump      ADJACENT or LONG",
            "#   camps     PASS_THROUGH or OPEN",
            "#   seed      seed of the playout; SplitMix64 (the stream of java.util.SplittableRandom, state += 0x9e3779b97f4a7c15)",
            "#   plies     plies played from the start position (11 * k + 5 with k = id mod " + PER_VARIANT
                    + ", fewer if the game ended earlier)",
            "#   side      the side to move: 0, 1 or 2",
            "#   pieces0   cells of player 0 (cell ids 0..120, ordered by r then q), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form; \"-\" with two players",
            "#   moves     number of legal moves of the side to move",
            "#   sorted    SHA-256 (lower-case hex) of the legal moves sorted ascending by (from, to)",
            "#   ordered   SHA-256 of the same moves in generation order (pieces by ascending cell; per piece the steps",
            "#             by direction, then the jump landings in depth-first order)",
            "# Move text that is hashed: one line per move, \"<from>-<to>\\n\" with decimal cell ids, UTF-8.",
            "# Playout: at every ply the legal moves are sorted ascending by (from, to); the move with index",
            "# (nextLong() >>> 1) % count is played, with nextLong() from SplitMix64(seed). seed = 0xF0C40000 + id.",
            "# A playout stops early if the game is over (outcome != null) or the side to move has no move.",
            "# Row order: camps (PASS_THROUGH, OPEN), then players (2, 3), then jump (ADJACENT, LONG), then k.");

    private ForeignCampsGolden() {
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < ROWS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    static RuleSet rules(int id) {
        int variant = id / PER_VARIANT;
        JumpRule jump = JumpRule.values()[variant % 2];
        int players = 2 + (variant / 2) % 2;
        ForeignCamps camps = CAMPS[variant / 4];
        return RuleSet.defaults(players).withJumpRule(jump).withForeignCamps(camps);
    }

    static long seed(int id) {
        return 0xF0C40000L + id;
    }

    static String line(int id) {
        RuleSet rules = rules(id);
        Position pos = Position.initial(rules);
        SplitMix64 random = new SplitMix64(seed(id));
        int target = 11 * (id % PER_VARIANT) + 5;
        while (pos.ply() < target && pos.outcome() == null) {
            int[] moves = LongJumpGolden.sorted(pos.legalMoves());
            if (moves.length == 0) {
                break;
            }
            pos.make(moves[(int) ((random.nextLong() >>> 1) % moves.length)]);
        }
        int[] generated = pos.legalMoves();
        return String.join("\t",
                Integer.toString(id), Integer.toString(rules.players()), rules.jumpRule().name(),
                rules.foreignCamps().name(), "0x" + Long.toHexString(seed(id)).toUpperCase(Locale.ROOT),
                Integer.toString(pos.ply()), Integer.toString(pos.sideToMove()),
                join(pos.pieces(0)), join(pos.pieces(1)), rules.players() == 3 ? join(pos.pieces(2)) : "-",
                Integer.toString(generated.length), LongJumpGolden.sha256(LongJumpGolden.sorted(generated)),
                LongJumpGolden.sha256(generated));
    }

    private static String join(int[] cells) {
        return String.join(",", Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    public static void main(String[] args) throws java.io.IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
