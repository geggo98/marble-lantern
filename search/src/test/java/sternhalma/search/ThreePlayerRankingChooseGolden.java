package sternhalma.search;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import sternhalma.engine.Layout;
import sternhalma.engine.Move;
import sternhalma.engine.Position;
import sternhalma.engine.RuleSet;
import sternhalma.engine.RuleSet.JumpRule;
import sternhalma.engine.RuleSet.Ranking;

/**
 * Generator of {@code three-player-ranking-choose-golden.tsv}, the file that the C++ port of {@link ThreePlayerSearch}
 * reproduces for {@code ranking=FULL_RANKING}: for positions with one finished player (and a few without), the move,
 * score, depth and node count of the three-player player at two node budgets. The format is documented in the header of
 * the file itself; {@code ThreePlayerRankingChooseGoldenTest} checks the committed file against a fresh run of this
 * generator. Rewrite the file with
 * {@code java -cp <engine, search main and test classes> sternhalma.search.ThreePlayerRankingChooseGolden <path>}.
 */
final class ThreePlayerRankingChooseGolden {

    static final int POSITIONS = 16;
    static final long[] BUDGETS = {5_000, 20_000};

    static final List<String> HEADER = List.of(
            "# Golden choices of the three-player player (ThreePlayerSpec \"ab3:eval=linear-r2,nodes=N,tt=16\", plus jump=long",
            "# for LONG rows) in the continued phase of ranking=FULL_RANKING: rules RuleSet.defaults(3) with FULL_RANKING, move",
            "# limit 600 and the jump rule of the row.",
            "# Generated by search/src/test/java/sternhalma/search/ThreePlayerRankingChooseGolden.java; checked by",
            "# ThreePlayerRankingChooseGoldenTest. The C++ port reproduces every column. One position per line, tab separated:",
            "#   id        position number, 0 to 15",
            "#   jump      ADJACENT or LONG (id % 2: 0 = ADJACENT, 1 = LONG)",
            "#   seed      seed of the playout; SplitMix64 (the stream of java.util.SplittableRandom, state += 0x9e3779b97f4a7c15)",
            "#   plies     plies played from the start position",
            "#   side      the side to move: 0, 1 or 2",
            "#   finished  the set of finished players as bits (bit p for player p), as Position.finishedMask()",
            "#   pieces0   cells of player 0 (cell ids 0..120, ordered by r then q), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form",
            "#   then, for the node budgets 5000 and 20000 in this order, five columns each, from a new player (empty table):",
            "#   move      the chosen move as <from>-<to> (cell ids)",
            "#   score     SearchResult.score (the paranoid score from the view of the side to move)",
            "#   depth     SearchResult.depth",
            "#   nodes     SearchResult.nodes",
            "#   complete  SearchResult.complete (true or false)",
            "# Playout: at every ply the legal moves are sorted ascending by (from, to); among the moves with the largest distance",
            "# gain Layout.distance(mover, from) - Layout.distance(mover, to) the one with index (nextLong() >>> 1) % (number of",
            "# such moves) in sorted order is played. It stops 2 * (id / 2) plies after the first player has finished (so rows 0",
            "# and 1 stop right after the first finish), or one ply before the game ends. nextLong() is from SplitMix64(seed),",
            "# seed = 0xC0DF0000 + id.");

    private ThreePlayerRankingChooseGolden() {
    }

    static JumpRule jumpOf(int id) {
        return id % 2 == 0 ? JumpRule.ADJACENT : JumpRule.LONG;
    }

    static RuleSet rules(JumpRule jump) {
        return RuleSet.defaults(3).withRanking(Ranking.FULL_RANKING).withMoveLimit(600).withJumpRule(jump);
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < POSITIONS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    /** The position of a row: the seeded playout of the header. */
    static Position position(int id) {
        Position pos = Position.initial(rules(jumpOf(id)));
        ThreePlayerChooseGolden.SplitMix64 random = new ThreePlayerChooseGolden.SplitMix64(0xC0DF0000L + id);
        int firstFinished = -1;
        int extra = 2 * (id / 2);
        while (pos.outcome() == null && !(firstFinished >= 0 && pos.ply() >= firstFinished + extra)) {
            int[] moves = ThreePlayerChooseGolden.sorted(pos.legalMoves());
            if (moves.length == 0) {
                break;
            }
            int[] candidates = bestGain(pos, moves);
            pos.make(candidates[(int) ((random.nextLong() >>> 1) % candidates.length)]);
            if (firstFinished < 0 && pos.finishedMask() != 0) {
                firstFinished = pos.ply();
            }
        }
        if (pos.outcome() != null) {
            pos.unmake(); // one ply before the end: the position can still be searched
        }
        return pos;
    }

    static String line(int id) {
        Position pos = position(id);
        List<String> fields = new ArrayList<>(List.of(
                Integer.toString(id), jumpOf(id).name(),
                "0x" + Long.toHexString(0xC0DF0000L + id).toUpperCase(),
                Integer.toString(pos.ply()), Integer.toString(pos.sideToMove()), Integer.toString(pos.finishedMask()),
                join(pos.pieces(0)), join(pos.pieces(1)), join(pos.pieces(2))));
        for (long budget : BUDGETS) {
            String spec = "ab3:eval=linear-r2,nodes=" + budget + ",tt=16"
                    + (jumpOf(id) == JumpRule.LONG ? ",jump=long" : "");
            SearchResult r = ThreePlayerSpec.parse(spec).create().analyse(pos);
            fields.add(Move.from(r.move()) + "-" + Move.to(r.move()));
            fields.add(Integer.toString(r.score()));
            fields.add(Integer.toString(r.depth()));
            fields.add(Long.toString(r.nodes()));
            fields.add(Boolean.toString(r.complete()));
        }
        return String.join("\t", fields);
    }

    private static int[] bestGain(Position pos, int[] sortedMoves) {
        int p = pos.sideToMove();
        Layout layout = pos.layout();
        int best = Integer.MIN_VALUE;
        int[] kept = new int[sortedMoves.length];
        int count = 0;
        for (int m : sortedMoves) {
            int gain = layout.distance(p, Move.from(m)) - layout.distance(p, Move.to(m));
            if (gain > best) {
                best = gain;
                count = 0;
            }
            if (gain == best) {
                kept[count++] = m;
            }
        }
        return Arrays.copyOf(kept, count);
    }

    private static String join(int[] cells) {
        return String.join(",", Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    public static void main(String[] args) throws java.io.IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
