package sternhalma.search;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import sternhalma.engine.Move;
import sternhalma.engine.Position;
import sternhalma.engine.RuleSet.JumpRule;

/**
 * Generator of {@code three-player-analyse-golden.tsv}, the file that the C++ port of the three-player analysis
 * reproduces: for the positions of {@link ThreePlayerChooseGolden} (seeded playouts, both jump rules), the analysis
 * score of every legal move at two node budgets and the static evaluation vector. {@code ThreePlayerAnalyseGoldenTest}
 * checks the committed file against a fresh run. Rewrite the file with
 * {@code java -cp <engine, search main and test classes> sternhalma.search.ThreePlayerAnalyseGolden <path>}.
 */
final class ThreePlayerAnalyseGolden {

    static final long[] BUDGETS = {2_000, 5_000};

    static final List<String> HEADER = List.of(
            "# Golden analysis of the three-player player (ThreePlayerPlayer.analyseMove with the spec",
            "# \"ab3:eval=linear-r2,nodes=N,tt=16\", plus jump=long for LONG rows) on the positions of three-player-choose-golden.tsv",
            "# (the same ids, seeds and playouts; see the header of that file for how a position is built).",
            "# Generated by search/src/test/java/sternhalma/search/ThreePlayerAnalyseGolden.java; checked by",
            "# ThreePlayerAnalyseGoldenTest. The C++ port reproduces every column. One position per line, tab separated:",
            "#   id        position number, 0 to 25",
            "#   jump      ADJACENT or LONG",
            "#   side      the side to move: 0, 1 or 2",
            "#   pieces0   cells of player 0 (cell ids 0..120), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form",
            "#   eval      the static evaluation vector ThreePlayerPlayer.evaluation: three integers, one per absolute player, comma separated",
            "#   then, for the node budgets 2000 and 5000 in this order, one column each: the scored legal moves, sorted ascending by",
            "#   (from, to), comma separated, each <from>-<to>:<score>:<depth>:<nodes> from SearchResult of analyseMove on a new",
            "#   player (the table is cleared before every move).",
            "# The analysis of any subset of the moves, in any order, gives the same per-move values; the tests check that against",
            "# these rows.");

    private ThreePlayerAnalyseGolden() {
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < ThreePlayerChooseGolden.POSITIONS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    static String spec(long budget, JumpRule jump) {
        return "ab3:eval=linear-r2,nodes=" + budget + ",tt=16" + (jump == JumpRule.LONG ? ",jump=long" : "");
    }

    static String line(int id) {
        Position pos = ThreePlayerChooseGolden.position(id);
        JumpRule jump = ThreePlayerChooseGolden.jumpOf(id);
        List<String> fields = new ArrayList<>(List.of(
                Integer.toString(id), jump.name(), Integer.toString(pos.sideToMove()),
                join(pos.pieces(0)), join(pos.pieces(1)), join(pos.pieces(2))));
        int[] eval = ThreePlayerSpec.parse(spec(1, jump)).create().evaluation(pos);
        fields.add(eval[0] + "," + eval[1] + "," + eval[2]);
        int[] moves = ThreePlayerChooseGolden.sorted(pos.legalMoves());
        for (long budget : BUDGETS) {
            ThreePlayerPlayer player = ThreePlayerSpec.parse(spec(budget, jump)).create();
            List<String> cells = new ArrayList<>();
            for (int move : moves) {
                SearchResult r = player.analyseMove(pos, move);
                cells.add(Move.from(move) + "-" + Move.to(move) + ":" + r.score() + ":" + r.depth() + ":" + r.nodes());
            }
            fields.add(String.join(",", cells));
        }
        return String.join("\t", fields);
    }

    private static String join(int[] cells) {
        return String.join(",", java.util.Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    public static void main(String[] args) throws IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
