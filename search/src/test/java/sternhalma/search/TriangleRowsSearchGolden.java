package sternhalma.search;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.SplittableRandom;

import sternhalma.engine.Layout;
import sternhalma.engine.Position;
import sternhalma.engine.RuleSet;
import sternhalma.engine.RuleSet.ForeignCamps;
import sternhalma.engine.RuleSet.JumpRule;
import sternhalma.engine.RuleSet.TriangleRows;

/**
 * Generator of {@code triangle-rows-search-golden.tsv}: static values and search results of the Java engine on the
 * 5-row board (15-cell houses), which the C++ engine ({@code cpp/tests/rows5_search_test.cpp}) reproduces bit for
 * bit. {@code TriangleRowsSearchGoldenTest} checks the committed file against a fresh run. Rewrite the file with
 * {@code java -cp <search classes>:<engine classes> sternhalma.search.TriangleRowsSearchGolden <path>}.
 */
final class TriangleRowsSearchGolden {

    static final int POSITIONS_PER_VARIANT = 12;
    /** Every k-th position of a variant is also searched. */
    static final int SEARCH_EVERY = 3;
    static final int NODES = 1500;
    static final long SEED_BASE = 0x5EA2C400L;

    static final List<String> HEADER = List.of(
            "# Golden values of the search on the 5-row board (RuleSet.TriangleRows FIVE: 15-cell houses, 15 pieces).",
            "# Generated by search/src/test/java/sternhalma/search/TriangleRowsSearchGolden.java; checked by",
            "# TriangleRowsSearchGoldenTest against a fresh run; reproduced by cpp/tests/rows5_search_test.cpp.",
            "# One position per line, tab separated, after this header. Columns:",
            "#   id        row number",
            "#   players   2 or 3",
            "#   jump      ADJACENT or LONG",
            "#   camps     CLOSED, PASS_THROUGH or OPEN",
            "#   ply       plies played from the start position",
            "#   side      the side to move",
            "#   pieces0..2  cells of players 0, 1 and 2 (ids 0..120), ascending, comma separated; \"-\" for player 2 with two players",
            "#   static    two players: linear-r1 and linear-r3 of Evaluators (side to move minus opponent), comma separated;",
            "#             three players: ThreePlayerPlayer.evaluation with eval=linear-r2, three values by absolute player",
            "#   search    \"-\" (not searched), or move,score,depth,nodes of choose() with " + NODES + " nodes: two players",
            "#             ab:eval=linear-r3,rows=5,tt=14 (+ jump=long), three players ab3:eval=linear-r2,rows=5,tt=14 (+ jump=long)",
            "# Positions: a playout per variant from the start position with SplittableRandom(0x5EA2C400 + variant). Each move",
            "# is, with probability 0.7, one with the largest gain Layout.distance(p, from) - Layout.distance(p, to) (the first",
            "# such move of the sorted list at index nextInt(count)), else a random move. Positions are recorded at ply 3 + 12 k.",
            "# Row order: camps (CLOSED, PASS_THROUGH, OPEN), players (2, 3), jump (ADJACENT, LONG), then k.");

    private TriangleRowsSearchGolden() {
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        int id = 0;
        int variant = 0;
        for (ForeignCamps camps : ForeignCamps.values()) {
            for (int players = 2; players <= 3; players++) {
                for (JumpRule jump : JumpRule.values()) {
                    RuleSet rules = RuleSet.defaults(players, TriangleRows.FIVE).withJumpRule(jump).withForeignCamps(camps);
                    SplittableRandom random = new SplittableRandom(SEED_BASE + variant++);
                    Position pos = Position.initial(rules);
                    Layout layout = pos.layout();
                    String spec = players == 2 ? "ab:eval=linear-r3,rows=5,tt=14" : "ab3:eval=linear-r2,rows=5,tt=14";
                    spec += (jump == JumpRule.LONG ? ",jump=long" : "") + ",nodes=" + NODES;
                    for (int k = 0; k < POSITIONS_PER_VARIANT; k++) {
                        while (pos.ply() < 3 + 12 * k && pos.outcome() == null) {
                            pos.make(next(pos, layout, random));
                        }
                        lines.add(line(id, rules, pos, spec, k % SEARCH_EVERY == 0));
                        id++;
                    }
                }
            }
        }
        return lines;
    }

    private static int next(Position pos, Layout layout, SplittableRandom random) {
        int[] moves = sorted(pos.legalMoves());
        if (random.nextInt(10) >= 7) {
            return moves[random.nextInt(moves.length)];
        }
        int p = pos.sideToMove();
        int best = Integer.MIN_VALUE;
        int count = 0;
        for (int m : moves) {
            int g = layout.distance(p, sternhalma.engine.Move.from(m)) - layout.distance(p, sternhalma.engine.Move.to(m));
            if (g > best) {
                best = g;
                count = 0;
            }
            if (g == best) {
                count++;
            }
        }
        int pick = random.nextInt(count);
        for (int m : moves) {
            int g = layout.distance(p, sternhalma.engine.Move.from(m)) - layout.distance(p, sternhalma.engine.Move.to(m));
            if (g == best && pick-- == 0) {
                return m;
            }
        }
        throw new AssertionError();
    }

    /** The moves ascending by (from, to). */
    private static int[] sorted(int[] moves) {
        return java.util.Arrays.stream(moves).boxed()
                .sorted(java.util.Comparator.comparingInt((Integer m) -> sternhalma.engine.Move.from(m))
                        .thenComparingInt(m -> sternhalma.engine.Move.to(m)))
                .mapToInt(Integer::intValue).toArray();
    }

    private static String cells(Position pos, int player) {
        if (player >= pos.rules().players()) {
            return "-";
        }
        int[] c = new int[pos.pieceCount(player)];
        for (int i = 0; i < c.length; i++) {
            c[i] = pos.pieceCell(player, i);
        }
        java.util.Arrays.sort(c);
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < c.length; i++) {
            sb.append(i == 0 ? "" : ",").append(c[i]);
        }
        return sb.toString();
    }

    private static String line(int id, RuleSet rules, Position pos, String spec, boolean search) {
        String statics;
        String searched = "-";
        if (rules.players() == 2) {
            statics = Evaluators.byName("linear-r1").evaluate(pos) + "," + Evaluators.byName("linear-r3").evaluate(pos);
            if (search) {
                AlphaBetaPlayer player = PlayerSpec.parse(spec).create();
                int move = player.choose(pos.copy());
                SearchResult r = player.lastResult();
                searched = move + "," + r.score() + "," + r.depth() + "," + r.nodes();
            }
        } else {
            ThreePlayerPlayer player = ThreePlayerSpec.parse(spec).create();
            int[] e = player.evaluation(pos.copy());
            statics = e[0] + "," + e[1] + "," + e[2];
            if (search) {
                int move = player.choose(pos.copy());
                SearchResult r = player.lastResult();
                searched = move + "," + r.score() + "," + r.depth() + "," + r.nodes();
            }
        }
        return String.join("\t", Integer.toString(id), Integer.toString(rules.players()), rules.jumpRule().name(),
                rules.foreignCamps().name(), Integer.toString(pos.ply()), Integer.toString(pos.sideToMove()),
                cells(pos, 0), cells(pos, 1), cells(pos, 2), statics, searched);
    }

    public static void main(String[] args) throws IOException {
        Files.write(Path.of(args[0]), (String.join("\n", lines()) + "\n").getBytes(StandardCharsets.UTF_8));
    }
}
