package sternhalma.search;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import sternhalma.engine.Move;
import sternhalma.engine.Position;
import sternhalma.engine.RuleSet.JumpRule;

/**
 * Generator of {@code three-player-ranking-analyse-golden.tsv}, the file that the C++ port of the three-player analysis
 * reproduces in the continued phase of {@code ranking=FULL_RANKING}: for the positions of
 * {@link ThreePlayerRankingChooseGolden} (the same ids and playouts), the static evaluation vector and the analysis score
 * of every legal move at two node budgets. {@code ThreePlayerRankingAnalyseGoldenTest} checks the committed file against
 * a fresh run. Rewrite the file with
 * {@code java -cp <engine, search main and test classes> sternhalma.search.ThreePlayerRankingAnalyseGolden <path>}.
 */
final class ThreePlayerRankingAnalyseGolden {

    static final long[] BUDGETS = {2_000, 5_000};

    static final List<String> HEADER = List.of(
            "# Golden analysis of the three-player player (ThreePlayerPlayer.analyseMove with the spec",
            "# \"ab3:eval=linear-r2,nodes=N,tt=16\", plus jump=long for LONG rows) on the positions of",
            "# three-player-ranking-choose-golden.tsv (ranking=FULL_RANKING; the same ids and playouts, see the header of that file).",
            "# Generated by search/src/test/java/sternhalma/search/ThreePlayerRankingAnalyseGolden.java; checked by",
            "# ThreePlayerRankingAnalyseGoldenTest. The C++ port reproduces every column. One position per line, tab separated:",
            "#   id        position number, 0 to 15",
            "#   jump      ADJACENT or LONG",
            "#   side      the side to move: 0, 1 or 2",
            "#   finished  the set of finished players as bits (bit p for player p)",
            "#   pieces0   cells of player 0 (cell ids 0..120), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form",
            "#   eval      ThreePlayerPlayer.evaluation: three integers, one per absolute player, comma separated; the seat of a",
            "#             finished player holds its rank constant (1000000 first, 500000 second, -1000000 last)",
            "#   then, for the node budgets 2000 and 5000 in this order, one column each: the scored legal moves, sorted ascending by",
            "#   (from, to), comma separated, each <from>-<to>:<score>:<depth>:<nodes> from SearchResult of analyseMove on a new",
            "#   player (the table is cleared before every move). A move that finishes the mover scores 999999 (first place) or",
            "#   499999 (second place) at depth 0 and 1 node.");

    private ThreePlayerRankingAnalyseGolden() {
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < ThreePlayerRankingChooseGolden.POSITIONS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    static String spec(long budget, JumpRule jump) {
        return "ab3:eval=linear-r2,nodes=" + budget + ",tt=16" + (jump == JumpRule.LONG ? ",jump=long" : "");
    }

    static String line(int id) {
        Position pos = ThreePlayerRankingChooseGolden.position(id);
        JumpRule jump = ThreePlayerRankingChooseGolden.jumpOf(id);
        List<String> fields = new ArrayList<>(List.of(
                Integer.toString(id), jump.name(), Integer.toString(pos.sideToMove()), Integer.toString(pos.finishedMask()),
                join(pos.pieces(0)), join(pos.pieces(1)), join(pos.pieces(2))));
        int[] eval = ThreePlayerSpec.parse(spec(1, jump)).create().evaluation(pos);
        fields.add(eval[0] + "," + eval[1] + "," + eval[2]);
        int[] moves = ThreePlayerChooseGolden.sorted(pos.legalMoves());
        for (long budget : BUDGETS) {
            ThreePlayerPlayer player = ThreePlayerSpec.parse(spec(budget, jump)).create();
            List<String> cells = new ArrayList<>();
            for (int move : moves) {
                SearchResult r = player.analyseMove(pos, move);
                cells.add(Move.from(move) + "-" + Move.to(move) + ":" + r.score() + ":" + r.depth() + ":" + r.nodes());
            }
            fields.add(String.join(",", cells));
        }
        return String.join("\t", fields);
    }

    private static String join(int[] cells) {
        return String.join(",", Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    public static void main(String[] args) throws IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
