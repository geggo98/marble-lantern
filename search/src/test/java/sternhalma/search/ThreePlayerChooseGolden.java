package sternhalma.search;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import sternhalma.engine.Layout;
import sternhalma.engine.Move;
import sternhalma.engine.Position;
import sternhalma.engine.RuleSet;
import sternhalma.engine.RuleSet.JumpRule;

/**
 * Generator of {@code three-player-choose-golden.tsv}, the file that the C++ port of {@link ThreePlayerSearch}
 * reproduces: for positions of seeded playouts, the move, score, depth and node count of the three-player player at
 * two node budgets. The format is documented in the header of the file itself (see {@link #HEADER});
 * {@code ThreePlayerChooseGoldenTest} checks the committed file against a fresh run of this generator. Rewrite the
 * file with {@code java -cp <engine, search main and test classes> sternhalma.search.ThreePlayerChooseGolden <path>}.
 */
final class ThreePlayerChooseGolden {

    static final int POSITIONS = 26;
    static final long[] BUDGETS = {5_000, 20_000};

    static final List<String> HEADER = List.of(
            "# Golden choices of the three-player player (ThreePlayerSpec \"ab3:eval=linear-r2,nodes=N,tt=16\", plus jump=long",
            "# for LONG rows) on positions of seeded playouts, rules RuleSet.defaults(3) with the jump rule of the row.",
            "# Generated by search/src/test/java/sternhalma/search/ThreePlayerChooseGolden.java; checked by",
            "# ThreePlayerChooseGoldenTest. The C++ port reproduces every column. One position per line, tab separated:",
            "#   id        position number, 0 to 25",
            "#   jump      ADJACENT or LONG (id % 2: 0 = ADJACENT, 1 = LONG)",
            "#   policy    RANDOM (ids 0 to 19) or GREEDY (ids 20 to 25)",
            "#   seed      seed of the playout; SplitMix64 (the stream of java.util.SplittableRandom, state += 0x9e3779b97f4a7c15)",
            "#   plies     plies played from the start position",
            "#   side      the side to move: 0, 1 or 2",
            "#   pieces0   cells of player 0 (cell ids 0..120, ordered by r then q), ascending, comma separated",
            "#   pieces1   cells of player 1, same form",
            "#   pieces2   cells of player 2, same form",
            "#   then, for the node budgets 5000 and 20000 in this order, five columns each, from a new player (empty table):",
            "#   move      the chosen move as <from>-<to> (cell ids)",
            "#   score     SearchResult.score (the paranoid score from the view of the side to move)",
            "#   depth     SearchResult.depth",
            "#   nodes     SearchResult.nodes",
            "#   complete  SearchResult.complete (true or false)",
            "# Playout: at every ply the legal moves are sorted ascending by (from, to). RANDOM: the move with index",
            "# (nextLong() >>> 1) % count is played, for 9 * id + id % 3 plies. GREEDY: among the moves with the largest distance gain",
            "# Layout.distance(mover, from) - Layout.distance(mover, to) the one with index (nextLong() >>> 1) % (number of such",
            "# moves) in sorted order is played, for 60 + 20 * (id - 20) plies (or until one ply before the game ends).",
            "# nextLong() is from SplitMix64(seed), seed = 0xC0DE0000 + id.");

    private ThreePlayerChooseGolden() {
    }

    /** The stream of {@code new SplittableRandom(seed).nextLong()}. */
    static final class SplitMix64 {
        private long seed;

        SplitMix64(long seed) {
            this.seed = seed;
        }

        long nextLong() {
            long z = seed += 0x9e3779b97f4a7c15L;
            z = (z ^ (z >>> 30)) * 0xbf58476d1ce4e5b9L;
            z = (z ^ (z >>> 27)) * 0x94d049bb133111ebL;
            return z ^ (z >>> 31);
        }
    }

    static JumpRule jumpOf(int id) {
        return id % 2 == 0 ? JumpRule.ADJACENT : JumpRule.LONG;
    }

    static RuleSet rules(JumpRule jump) {
        return RuleSet.defaults(3).withJumpRule(jump);
    }

    static List<String> lines() {
        List<String> lines = new ArrayList<>(HEADER);
        for (int id = 0; id < POSITIONS; id++) {
            lines.add(line(id));
        }
        return lines;
    }

    /** The position of a row: the seeded playout of the header. */
    static Position position(int id) {
        boolean greedy = id >= 20;
        Position pos = Position.initial(rules(jumpOf(id)));
        SplitMix64 random = new SplitMix64(0xC0DE0000L + id);
        int target = greedy ? 60 + 20 * (id - 20) : 9 * id + id % 3;
        while (pos.ply() < target && pos.outcome() == null) {
            int[] moves = sorted(pos.legalMoves());
            if (moves.length == 0) {
                break;
            }
            int[] candidates = greedy ? bestGain(pos, moves) : moves;
            pos.make(candidates[(int) ((random.nextLong() >>> 1) % candidates.length)]);
        }
        if (pos.outcome() != null) {
            pos.unmake(); // one ply before the end: the position can still be searched
        }
        return pos;
    }

    static String line(int id) {
        Position pos = position(id);
        List<String> fields = new ArrayList<>(List.of(
                Integer.toString(id), jumpOf(id).name(), id >= 20 ? "GREEDY" : "RANDOM",
                "0x" + Long.toHexString(0xC0DE0000L + id).toUpperCase(),
                Integer.toString(pos.ply()), Integer.toString(pos.sideToMove()),
                join(pos.pieces(0)), join(pos.pieces(1)), join(pos.pieces(2))));
        for (long budget : BUDGETS) {
            String spec = "ab3:eval=linear-r2,nodes=" + budget + ",tt=16"
                    + (jumpOf(id) == JumpRule.LONG ? ",jump=long" : "");
            SearchResult r = ThreePlayerSpec.parse(spec).create().analyse(pos);
            fields.add(Move.from(r.move()) + "-" + Move.to(r.move()));
            fields.add(Integer.toString(r.score()));
            fields.add(Integer.toString(r.depth()));
            fields.add(Long.toString(r.nodes()));
            fields.add(Boolean.toString(r.complete()));
        }
        return String.join("\t", fields);
    }

    private static int[] bestGain(Position pos, int[] sortedMoves) {
        int p = pos.sideToMove();
        Layout layout = pos.layout();
        int best = Integer.MIN_VALUE;
        int[] kept = new int[sortedMoves.length];
        int count = 0;
        for (int m : sortedMoves) {
            int gain = layout.distance(p, Move.from(m)) - layout.distance(p, Move.to(m));
            if (gain > best) {
                best = gain;
                count = 0;
            }
            if (gain == best) {
                kept[count++] = m;
            }
        }
        return Arrays.copyOf(kept, count);
    }

    /** Sorted ascending by (from, to). */
    static int[] sorted(int[] moves) {
        return Arrays.stream(moves).boxed()
                .sorted((x, y) -> Integer.compare(Move.from(x) << 8 | Move.to(x), Move.from(y) << 8 | Move.to(y)))
                .mapToInt(Integer::intValue).toArray();
    }

    private static String join(int[] cells) {
        return String.join(",", Arrays.stream(cells).mapToObj(Integer::toString).toList());
    }

    public static void main(String[] args) throws java.io.IOException {
        Files.write(Path.of(args[0]), lines(), StandardCharsets.UTF_8);
    }
}
